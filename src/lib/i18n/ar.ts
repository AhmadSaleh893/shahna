const pluralRules = new Intl.PluralRules("ar");

/** Arabic has six plural forms; "#" is replaced with the number. */
function plural(n: number, forms: Record<Intl.LDMLPluralRule, string>) {
  return forms[pluralRules.select(n)].replace("#", String(n));
}

